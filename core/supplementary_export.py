"""
Supplementary Export — Data that URDF cannot carry.

Generates:
  - robot_data.yaml: Assembly hierarchy, per-link physics, rigid groups, materials
  - transforms.md:   KaTeX-formatted 4×4 homogeneous transformation matrices

Assemblies tagged "!dummy_*" are excluded
(placeholder convention).

Author: Adrian Valaker Eikeland
"""

import os
import math
from typing import Dict, List, Tuple

from .data_types import (
    RobotModel, LinkNode, JointNode, ExportConfig, Vec3, RPY,
    EXPORTER_VERSION,
)
from ..utils import Logger, is_dummy_assembly_name, yaml_safe_name


# ──────────────────────────────────────────────
# YAML export
# ──────────────────────────────────────────────

def generate_supplementary_yaml(
    model: RobotModel,
    config: ExportConfig,
    pkg_dir: str,
    log: Logger,
) -> str:
    """
    Generate robot_data.yaml with information URDF cannot carry.
    
    Dummy assemblies ("!dummy_*") are
    excluded — these are placeholders meant to be swapped out.
    """
    path = os.path.join(pkg_dir, "robot_data.yaml")
    lines = []
    
    # ── Metadata ──
    lines.append("# Supplementary robot data (beyond URDF)")
    lines.append(f"# Generated by Fusion URDF/XACRO Exporter")
    lines.append("")
    lines.append("metadata:")
    lines.append(f"  design_name: {model.name}")
    lines.append(f"  package_name: {config.package_name}")
    lines.append(f"  exporter_version: '{EXPORTER_VERSION}'")
    lines.append(f"  total_mass_kg: {sum(l.mass_kg for l in model.links.values()):.4f}")
    lines.append(f"  link_count: {len(model.links)}")
    lines.append(f"  joint_count: {len(model.joints)}")
    lines.append(f"  root_link: {model.root_link}")
    lines.append("")
    
    # ── Assemblies (skip dummy modules) ──
    real_assemblies = {
        name: asm for name, asm in model.assemblies.items()
        if not is_dummy_assembly_name(name)
    }
    
    if real_assemblies:
        lines.append("assemblies:")
        for name, asm in sorted(real_assemblies.items()):
            lines.append(f"  {name}:")
            lines.append(f"    links: [{', '.join(asm.links)}]")
            total_mass = sum(
                model.links[ln].mass_kg
                for ln in asm.links if ln in model.links
            )
            lines.append(f"    total_mass_kg: {total_mass:.4f}")
        lines.append("")
    
    # ── Links (skip those in dummy assemblies) ──
    dummy_assemblies = {
        name for name in model.assemblies if is_dummy_assembly_name(name)
    }
    
    lines.append("links:")
    for name in sorted(model.links.keys()):
        link = model.links[name]
        if link.assembly in dummy_assemblies:
            continue
        lines.append(f"  {name}:")
        lines.append(f"    assembly: {link.assembly}")
        lines.append(f"    mass_kg: {link.mass_kg:.6f}")
        lines.append(f"    volume_m3: {link.volume_m3:.8f}")
        
        bx, by, bz = link.bbox_size
        lines.append(f"    bbox_size_m: [{bx:.6f}, {by:.6f}, {bz:.6f}]")
        
        cx, cy, cz = link.com_link_local
        lines.append(f"    com_local_m: [{cx:.6f}, {cy:.6f}, {cz:.6f}]")
        
        inertia = link.inertia_at_com
        lines.append(f"    inertia_at_com:")
        lines.append(f"      ixx: {inertia.ixx:.6e}")
        lines.append(f"      ixy: {inertia.ixy:.6e}")
        lines.append(f"      ixz: {inertia.ixz:.6e}")
        lines.append(f"      iyy: {inertia.iyy:.6e}")
        lines.append(f"      iyz: {inertia.iyz:.6e}")
        lines.append(f"      izz: {inertia.izz:.6e}")
        
        if link.material_name:
            lines.append(f"    material: '{link.material_name}'")
        if link.color_rgb:
            r, g, b = link.color_rgb
            lines.append(f"    color_rgba: [{r:.3f}, {g:.3f}, {b:.3f}, 1.0]")
        
        lines.append(f"    body_count: {link.body_count}")
        lines.append(f"    is_empty: {str(link.is_empty).lower()}")
        if getattr(link, "is_frame_only", False):
            lines.append("    is_frame_only: true")
        if getattr(link, "collision_override", ""):
            lines.append(f"    collision_override: {link.collision_override}")
        
        if link.collision:
            lines.append(f"    collision_source: {link.collision.source}")
            if link.collision.uses_primitive and link.collision.primitive:
                lines.append(f"    collision_shape: {link.collision.primitive.shape}")
        
        if link.needs_mesh_bake:
            bk = link.mesh_bake_offset
            lines.append(f"    bake_offset_m: [{bk[0]:.6f}, {bk[1]:.6f}, {bk[2]:.6f}]")
            mr = getattr(link, "mesh_origin_rpy", (0.0, 0.0, 0.0))
            lines.append(
                f"    mesh_origin_rpy_rad: "
                f"[{mr[0]:.6f}, {mr[1]:.6f}, {mr[2]:.6f}]"
            )

        frame_rule = getattr(link, "frame_rule", "keep")
        if frame_rule != "keep":
            fr = getattr(link, "frame_rebase_rpy", (0.0, 0.0, 0.0))
            lines.append(f"    frame_rule: {frame_rule}")
            lines.append(
                f"    frame_rebase_rpy_rad: "
                f"[{fr[0]:.6f}, {fr[1]:.6f}, {fr[2]:.6f}]"
            )
        
        if link.rigid_group_name:
            lines.append(f"    rigid_group: {yaml_safe_name(link.rigid_group_name)}")

        if getattr(link, "is_merged", False) and link.merged_member_paths:
            # List the original Fusion components folded into this URDF
            # link so a downstream consumer can trace mass/inertia back
            # to its constituents.  Names only — paths would be noisy.
            members = []
            for occ_path in link.merged_member_paths:
                # path_segments[-1] is the component name; we stored that
                # via clean_name in the snapshot, but here we only have
                # the path.  Strip down to the leaf segment.
                leaf = occ_path.rsplit('+', 1)[-1].split(' ', 1)[0]
                # ``!frame_*`` / ``!collision_*`` source names land here
                # unstripped; ``!`` is a YAML tag marker so we drop it.
                members.append(yaml_safe_name(leaf or occ_path))
            lines.append(f"    is_merged: true")
            lines.append(f"    merged_from: [{', '.join(members)}]")
    
    lines.append("")
    
    # ── Joints (skip those involving dummy_ assembly links) ──
    dummy_links = {
        name for name, link in model.links.items()
        if link.assembly in dummy_assemblies
    }
    
    lines.append("joints:")
    for name in sorted(model.joints.keys()):
        joint = model.joints[name]
        if joint.parent_link in dummy_links or joint.child_link in dummy_links:
            continue
        lines.append(f"  {name}:")
        lines.append(f"    type: {joint.joint_type}")
        lines.append(f"    parent: {joint.parent_link}")
        lines.append(f"    child: {joint.child_link}")

        x, y, z = joint.origin_xyz
        lines.append(f"    origin_xyz_m: [{x:.6f}, {y:.6f}, {z:.6f}]")

        r, p, yw = joint.origin_rpy
        lines.append(f"    origin_rpy_rad: [{r:.6f}, {p:.6f}, {yw:.6f}]")

        ax, ay, az = joint.axis
        lines.append(f"    axis: [{ax:.4f}, {ay:.4f}, {az:.4f}]")

        lines.append(f"    is_mount: {str(joint.is_mount).lower()}")
        # ``passive`` tells downstream consumers (e.g. URDF→USD
        # importers) not to attach a position/velocity/effort drive on
        # this joint.  Plugin sets it for joints tagged ``!passive_*``
        # in Fusion (idler wheels, free pivots, four-bar followers).
        lines.append(f"    passive: {str(getattr(joint, 'is_passive', False)).lower()}")

        if joint.limits:
            lines.append(f"    limits:")
            lines.append(f"      lower: {joint.limits.lower:.6f}")
            lines.append(f"      upper: {joint.limits.upper:.6f}")
            lines.append(f"      effort: {joint.limits.effort:.1f}")
            lines.append(f"      velocity: {joint.limits.velocity:.2f}")

    # ── Closing joints (sidecar — closed kinematic chains) ──
    # Joints excluded from the URDF tree because URDF can't model
    # cycles.  Downstream URDF→USD pipelines re-apply these as
    # independent ``UsdPhysics*Joint`` prims (no DriveAPI — passive
    # constraints).  Implicitly all closing joints are passive.
    closing_joints = getattr(model, "closing_joints", None) or {}
    visible_closing = {
        n: j for n, j in closing_joints.items()
        if j.parent_link not in dummy_links and j.child_link not in dummy_links
    }
    lines.append("")
    if visible_closing:
        lines.append("closing_joints:")
        for name in sorted(visible_closing.keys()):
            joint = visible_closing[name]
            lines.append(f"  - name: {name}")
            lines.append(f"    source: {joint.closing_source or 'user_tag'}")
            lines.append(f"    type: {joint.joint_type}")
            lines.append(f"    parent: {joint.parent_link}")
            lines.append(f"    child: {joint.child_link}")

            x, y, z = joint.origin_xyz
            lines.append(f"    origin_xyz_m: [{x:.6f}, {y:.6f}, {z:.6f}]")

            r, p, yw = joint.origin_rpy
            lines.append(f"    origin_rpy_rad: [{r:.6f}, {p:.6f}, {yw:.6f}]")

            ax, ay, az = joint.axis
            lines.append(f"    axis: [{ax:.4f}, {ay:.4f}, {az:.4f}]")

            if joint.limits:
                lines.append(f"    limits:")
                lines.append(f"      lower: {joint.limits.lower:.6f}")
                lines.append(f"      upper: {joint.limits.upper:.6f}")
                lines.append(f"      effort: {joint.limits.effort:.1f}")
                lines.append(f"      velocity: {joint.limits.velocity:.2f}")
    else:
        # Emit an empty section so consumers can rely on the key
        # existing.  ``[]`` is YAML for an empty sequence.
        lines.append("closing_joints: []")

    lines.append("")

    # ── Rigid groups ──
    rg_data = getattr(model, '_rigid_group_collision', {})
    if rg_data:
        lines.append("rigid_groups:")
        # Group by rg_name
        groups: Dict[str, List[str]] = {}
        collision_from: Dict[str, str] = {}
        for member_name, (_, _, rg_name, coll_member) in rg_data.items():
            groups.setdefault(rg_name, []).append(member_name)
            collision_from[rg_name] = coll_member
        for rg_name, members in sorted(groups.items()):
            lines.append(f"  {rg_name}:")
            lines.append(f"    members: [{', '.join(sorted(members))}]")
            lines.append(f"    collision_from: {collision_from[rg_name]}")
    
    with open(path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')
    
    log(f"  → {os.path.relpath(path, pkg_dir)}")
    return path


