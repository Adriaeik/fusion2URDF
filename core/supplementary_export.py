def _rpy_to_rotation_matrix(
    roll: float, pitch: float, yaw: float
) -> List[List[float]]:
    """Convert RPY (XYZ extrinsic) to 3×3 rotation matrix."""
    cr, sr = math.cos(roll), math.sin(roll)
    cp, sp = math.cos(pitch), math.sin(pitch)
    cy, sy = math.cos(yaw), math.sin(yaw)
    
    return [
        [cy*cp,  cy*sp*sr - sy*cr,  cy*sp*cr + sy*sr],
        [sy*cp,  sy*sp*sr + cy*cr,  sy*sp*cr - cy*sr],
        [-sp,    cp*sr,             cp*cr],
    ]


def _fmt(v: float) -> str:
    """Format a float for KaTeX (clean trailing zeros)."""
    if abs(v) < 1e-10:
        return "0"
    if abs(v - round(v)) < 1e-10:
        return str(int(round(v)))
    s = f"{v:.6f}".rstrip('0').rstrip('.')
    if s == "-0":
        return "0"
    return s


def generate_transforms_doc(
    model: RobotModel,
    pkg_dir: str,
    log: Logger,
) -> str:
    """
    Generate transforms.md with KaTeX 4x4 homogeneous matrices.
    
    Revolute/continuous joints use symbolic q_i with c_i = cos(q_i), s_i = sin(q_i).
    Prismatic joints use symbolic q_i for translation along axis.
    Fixed joints produce numeric matrices.
    Global transforms are expressed as matrix products.
    """
    path = os.path.join(pkg_dir, "docs", "transforms.md")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    
    lines = []
    lines.append(f"# Transformation Matrices - {model.name}")
    lines.append("")
    lines.append("Homogeneous transformation matrices between consecutive frames.")
    lines.append("Convention: URDF RPY (XYZ extrinsic / ZYX intrinsic).")
    lines.append("")
    
    # Build kinematic chain order and assign indices
    joint_list = _kinematic_order(model)
    
    # Assign q indices only to movable joints
    q_index = {}  # joint.name -> index (1-based)
    idx = 1
    for joint in joint_list:
        if joint.joint_type in ("revolute", "prismatic", "continuous"):
            q_index[joint.name] = idx
            idx += 1
    
    # Assign link indices (0-based, root = 0, BFS order)
    link_index = {}  # link_name -> index
    link_order_list = []
    visited = {model.root_link}
    queue = [model.root_link]
    li = 0
    while queue:
        current = queue.pop(0)
        link_index[current] = li
        link_order_list.append(current)
        li += 1
        for joint in joint_list:
            if joint.parent_link == current and joint.child_link not in visited:
                visited.add(joint.child_link)
                queue.append(joint.child_link)
    
    # Notation section
    lines.append("## Notation")
    lines.append("")
    
    # Link table
    lines.append("### Frames")
    lines.append("")
    lines.append("| Index | Link |")
    lines.append("|-------|------|")
    for lname in link_order_list:
        li = link_index[lname]
        lines.append(f"| $L_{{{li}}}$ | {lname} |")
    lines.append("")
    
    # Joint / variable table
    if q_index:
        lines.append("### Joint Variables")
        lines.append("")
        lines.append("| Variable | Joint | Type | From | To |")
        lines.append("|----------|-------|------|------|----|")
        for joint in joint_list:
            if joint.name in q_index:
                i = q_index[joint.name]
                unit = "m" if joint.joint_type == "prismatic" else "rad"
                pi = link_index[joint.parent_link]
                ci_idx = link_index[joint.child_link]
                lines.append(f"| $q_{{{i}}}$ | {joint.name} | "
                              f"{joint.joint_type} ({unit}) | "
                              f"$L_{{{pi}}}$ | $L_{{{ci_idx}}}$ |")
        lines.append("")
        lines.append("Shorthand: $c_i = \\cos(q_i)$, $s_i = \\sin(q_i)$")
        lines.append("")
    
    # Kinematic tree diagram
    lines.append("### Kinematic Tree")
    lines.append("")
    lines.append("```")
    _build_notation_tree(lines, model, joint_list, link_index, q_index)
    lines.append("```")
    lines.append("")
    
    # Table of contents
    lines.append("## Transforms")
    lines.append("")
    
    # Generate per-joint transforms
    for joint in joint_list:
        i = q_index.get(joint.name)
        pi = link_index[joint.parent_link]
        ci_idx = link_index[joint.child_link]
        lines.append(f"## {joint.name}")
        lines.append("")
        lines.append(f"$L_{{{pi}}}$ **{joint.parent_link}** -> "
                      f"$L_{{{ci_idx}}}$ **{joint.child_link}** "
                      f"({joint.joint_type})")
        if i:
            lines.append(f"  Variable: $q_{{{i}}}$")
        lines.append("")
        
        # Parameters
        x, y, z = joint.origin_xyz
        r, p, yw = joint.origin_rpy
        lines.append(f"- **origin xyz**: ({_fmt(x)}, {_fmt(y)}, {_fmt(z)}) m")
        lines.append(f"- **origin rpy**: ({_fmt(r)}, {_fmt(p)}, {_fmt(yw)}) rad")
        if joint.joint_type in ("revolute", "prismatic", "continuous"):
            ax = joint.axis
            lines.append(f"- **axis**: ({_fmt(ax[0])}, {_fmt(ax[1])}, {_fmt(ax[2])})")
            if joint.limits:
                if joint.joint_type == "prismatic":
                    lines.append(f"- **limits**: [{_fmt(joint.limits.lower)}, "
                                  f"{_fmt(joint.limits.upper)}] m")
                else:
                    lines.append(f"- **limits**: [{_fmt(joint.limits.lower)}, "
                                  f"{_fmt(joint.limits.upper)}] rad "
                                  f"([{_fmt(math.degrees(joint.limits.lower))}deg, "
                                  f"{_fmt(math.degrees(joint.limits.upper))}deg])")
        lines.append("")
        
        # Local transform matrix
        lines.append("### Local Transform")
        lines.append("")
        
        if joint.joint_type == "fixed":
            # Numeric matrix
            R = _rpy_to_rotation_matrix(r, p, yw)
            lines.append("$$")
            lines.append(f"T^{{{pi}}}_{{{ci_idx}}} = "
                          f"\\begin{{bmatrix}}")
            for row_idx in range(3):
                entries = [_fmt(R[row_idx][j]) for j in range(3)]
                entries.append(_fmt([x, y, z][row_idx]))
                lines.append(" & ".join(entries) + " \\\\")
            lines.append("0 & 0 & 0 & 1 \\\\")
            lines.append("\\end{bmatrix}")
            lines.append("$$")
        
        elif joint.joint_type in ("revolute", "continuous"):
            # Symbolic matrix with rotation about axis
            ax = joint.axis
            _write_symbolic_revolute(lines, joint, i, x, y, z, r, p, yw, ax, pi, ci_idx)
        
        elif joint.joint_type == "prismatic":
            # Symbolic matrix with translation along axis
            ax = joint.axis
            _write_symbolic_prismatic(lines, joint, i, x, y, z, r, p, yw, ax, pi, ci_idx)
        
        lines.append("")
        lines.append("---")
        lines.append("")
    
    # Global transform chain
    lines.append("## Global Transform Chains")
    lines.append("")
    lines.append("Transform from root $L_0$ to any link, as product of "
                  "local transforms along the kinematic chain.")
    lines.append("")
    
    # Build parent map
    parent_chain: Dict[str, List[str]] = {}
    for joint in joint_list:
        chain = parent_chain.get(joint.parent_link, []).copy()
        chain.append(joint.name)
        parent_chain[joint.child_link] = chain
    
    for joint in joint_list:
        chain = parent_chain.get(joint.child_link, [])
        if len(chain) <= 1:
            continue
        
        ci_idx = link_index[joint.child_link]
        factors = []
        for jn in chain:
            jj = model.joints[jn]
            pi = link_index[jj.parent_link]
            cj = link_index[jj.child_link]
            qi = q_index.get(jn)
            if qi:
                factors.append(f"T^{{{pi}}}_{{{cj}}}(q_{{{qi}}})")
            else:
                factors.append(f"T^{{{pi}}}_{{{cj}}}")
        
        child_name = joint.child_link
        chain_str = ' \\cdot '.join(factors)
        lines.append(f"$$T^{{0}}_{{{ci_idx}}} = "
                      f"{chain_str}"
                      f"\\quad (L_0 \\to L_{{{ci_idx}}}: \\text{{{child_name}}})$$")
        lines.append("")
    
    with open(path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')
    
    log(f"  -> docs/transforms.md")
    return path


def _write_symbolic_revolute(
    lines: list, joint, i: int,
    tx: float, ty: float, tz: float,
    roll: float, pitch: float, yaw: float,
    axis: tuple,
    pi: int = 0, ci_idx: int = 0,
):
    """Write symbolic 4x4 for revolute joint with Rot(axis, q_i)."""
    ci = f"c_{{{i}}}"
    si = f"s_{{{i}}}"
    t_label = f"T^{{{pi}}}_{{{ci_idx}}}(q_{{{i}}})"
    
    # Pre-rotation from fixed RPY offset
    R_fixed = _rpy_to_rotation_matrix(roll, pitch, yaw)
    has_fixed_rot = any(
        abs(R_fixed[r][c] - (1 if r == c else 0)) > 1e-10
        for r in range(3) for c in range(3)
    )
    
    # Determine rotation axis
    ax, ay, az = axis
    
    if has_fixed_rot:
        # Complex case: T = T_fixed * Rot(axis, q_i)
        lines.append(f"${t_label} = T_{{fixed}} \\cdot R_{{axis}}(q_{{{i}}})$ where:")
        lines.append("")
        # Show fixed part
        lines.append("$$")
        lines.append(f"T_{{fixed}} = \\begin{{bmatrix}}")
        for row_idx in range(3):
            entries = [_fmt(R_fixed[row_idx][j]) for j in range(3)]
            entries.append(_fmt([tx, ty, tz][row_idx]))
            lines.append(" & ".join(entries) + " \\\\")
        lines.append("0 & 0 & 0 & 1 \\\\")
        lines.append("\\end{bmatrix}")
        lines.append("$$")
        lines.append("")
    
    # Show rotation matrix about axis
    label = t_label if not has_fixed_rot else f"R_{{axis}}(q_{{{i}}})"
    lines.append("$$")
    if abs(az) > 0.9:
        # Rotation about Z
        sign = "" if az > 0 else "-"
        nsign = "-" if az > 0 else ""
        lines.append(f"{label} = \\begin{{bmatrix}}")
        lines.append(f"{ci} & {nsign}{si} & 0 & {_fmt(tx) if not has_fixed_rot else '0'} \\\\")
        lines.append(f"{sign}{si} & {ci} & 0 & {_fmt(ty) if not has_fixed_rot else '0'} \\\\")
        lines.append(f"0 & 0 & 1 & {_fmt(tz) if not has_fixed_rot else '0'} \\\\")
        lines.append("0 & 0 & 0 & 1 \\\\")
    elif abs(ay) > 0.9:
        # Rotation about Y
        sign = "" if ay > 0 else "-"
        nsign = "-" if ay > 0 else ""
        lines.append(f"{label} = \\begin{{bmatrix}}")
        lines.append(f"{ci} & 0 & {sign}{si} & {_fmt(tx) if not has_fixed_rot else '0'} \\\\")
        lines.append(f"0 & 1 & 0 & {_fmt(ty) if not has_fixed_rot else '0'} \\\\")
        lines.append(f"{nsign}{si} & 0 & {ci} & {_fmt(tz) if not has_fixed_rot else '0'} \\\\")
        lines.append("0 & 0 & 0 & 1 \\\\")
    elif abs(ax) > 0.9:
        # Rotation about X
        sign = "" if ax > 0 else "-"
        nsign = "-" if ax > 0 else ""
        lines.append(f"{label} = \\begin{{bmatrix}}")
        lines.append(f"1 & 0 & 0 & {_fmt(tx) if not has_fixed_rot else '0'} \\\\")
        lines.append(f"0 & {ci} & {nsign}{si} & {_fmt(ty) if not has_fixed_rot else '0'} \\\\")
        lines.append(f"0 & {sign}{si} & {ci} & {_fmt(tz) if not has_fixed_rot else '0'} \\\\")
        lines.append("0 & 0 & 0 & 1 \\\\")
    else:
        # General axis - Rodrigues
        lines.append(f"{label} = "
                      f"\\text{{Rodrigues}}(\\hat{{k}}, q_{{{i}}})")
        lines.append("\\\\")
    
    lines.append("\\end{bmatrix}")
    lines.append("$$")


def _write_symbolic_prismatic(
    lines: list, joint, i: int,
    tx: float, ty: float, tz: float,
    roll: float, pitch: float, yaw: float,
    axis: tuple,
    pi: int = 0, ci_idx: int = 0,
):
    """Write symbolic 4x4 for prismatic joint with Trans(axis, q_i)."""
    R_fixed = _rpy_to_rotation_matrix(roll, pitch, yaw)
    ax, ay, az = axis
    qi = f"q_{{{i}}}"
    
    # Translation components: fixed + q_i * axis
    def _tx_sym(fixed_val, axis_comp):
        f = _fmt(fixed_val)
        if abs(axis_comp) > 0.9:
            sign = "+" if axis_comp > 0 else "-"
            return f"{f} {sign} {qi}" if f != "0" else f"{'' if axis_comp > 0 else '-'}{qi}"
        return f
    
    tx_s = _tx_sym(tx, ax)
    ty_s = _tx_sym(ty, ay)
    tz_s = _tx_sym(tz, az)
    
    lines.append("$$")
    lines.append(f"T^{{{pi}}}_{{{ci_idx}}}(q_{{{i}}}) = "
                  f"\\begin{{bmatrix}}")
    for row_idx in range(3):
        entries = [_fmt(R_fixed[row_idx][j]) for j in range(3)]
        entries.append([tx_s, ty_s, tz_s][row_idx])
        lines.append(" & ".join(entries) + " \\\\")
    lines.append("0 & 0 & 0 & 1 \\\\")
    lines.append("\\end{bmatrix}")
    lines.append("$$")


def _kinematic_order(model: RobotModel) -> List[JointNode]:
    """Return joints in kinematic tree order (BFS from root)."""
    ordered = []
    visited = {model.root_link}
    queue = [model.root_link]
    
    # Build child map
    children: Dict[str, List[JointNode]] = {}
    for j in model.joints.values():
        children.setdefault(j.parent_link, []).append(j)
    
    while queue:
        current = queue.pop(0)
        for joint in children.get(current, []):
            if joint.child_link not in visited:
                ordered.append(joint)
                visited.add(joint.child_link)
                queue.append(joint.child_link)
    
    return ordered


def _build_notation_tree(
    lines: list,
    model: RobotModel,
    joint_list: list,
    link_index: Dict[str, int],
    q_index: Dict[str, int],
    link: str = None,
    prefix: str = "",
    is_last: bool = True,
):
    """Build ASCII kinematic tree with L_i indices and q_i labels."""
    if link is None:
        link = model.root_link
    
    li = link_index.get(link, "?")
    lines.append(f"{prefix}L{li}: {link}")
    
    # Find children
    children = []
    for joint in joint_list:
        if joint.parent_link == link:
            children.append(joint)
    
    for idx, joint in enumerate(children):
        is_last_child = (idx == len(children) - 1)
        connector = "  +-- " if is_last_child else "  |-- "
        qi = q_index.get(joint.name)
        q_label = f" (q{qi})" if qi else ""
        
        lines.append(f"{prefix}{connector}[{joint.joint_type}] {joint.name}{q_label}")
        
        child_prefix = prefix + ("      " if is_last_child else "  |   ")
        _build_notation_tree(
            lines, model, joint_list, link_index, q_index,
            joint.child_link, child_prefix, is_last_child,
        )


def _mat_mul_4x4(A: List[List[float]], B: List[List[float]]) -> List[List[float]]:
    """Multiply two 4×4 matrices."""
    result = [[0.0]*4 for _ in range(4)]
    for i in range(4):
        for j in range(4):
            for k in range(4):
                result[i][j] += A[i][k] * B[k][j]
    return result
